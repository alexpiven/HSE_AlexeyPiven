# Главное меню
def main_menu():
    keyboard = [
        [KeyboardButton("Случайный анекдот")],
        [KeyboardButton("Про программистов"), KeyboardButton("Про животных")],
        [KeyboardButton("Про врачей"), KeyboardButton("Про школу")],
        [KeyboardButton("Про любовь"), KeyboardButton("Про армию")],
        [KeyboardButton("Про политику"), KeyboardButton("Про чукч")],
        [KeyboardButton("Еврейские анекдоты"), KeyboardButton("Общие")]
    ]
    return ReplyKeyboardMarkup(keyboard, resize_keyboard=True)

# Обработчик команды /start
async def start(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    await update.message.reply_text(
        "😄 Привет! Я бот с анекдотами из книги «АНЕКДОТЫ ОТ АКАДЕМИКА». Выбери категорию:",
        reply_markup=main_menu()
    )

# Обработчик сообщений
async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE) -> None:
    text = update.message.text

    if text == "Про программистов":
        category = "jokes_general"  # В книге нет анекдотов про программистов, используем общие
    elif text == "Про животных":
        category = "jokes_animals"
    elif text == "Про врачей":
        category = "jokes_general"  # В книге нет отдельной категории, используем общие
    elif text == "Про школу":
        category = "jokes_school"
    elif text == "Про любовь":
        category = "jokes_love"
    elif text == "Про армию":
        category = "jokes_army"
    elif text == "Про политику":
        category = "jokes_politics"
    elif text == "Про чукч":
        category = "jokes_chukchi"
    elif text == "Еврейские анекдоты":
        category = "jokes_jewish"
    elif text == "Общие":
        category = "jokes_general"
    elif text == "Случайный анекдот":
        all_jokes = []
        for cat in anecdotes.values():
            all_jokes.extend(cat)
        response = random.choice(all_jokes)
        await update.message.reply_text(response)
        return
    else:
        response = "Пожалуйста, выбери категорию из меню 🤣"
        await update.message.reply_text(response)
        return

    try:
        response = random.choice(anecdotes[category])
    except KeyError:
        response = "Анекдоты в этой категории пока отсутствуют."

    await update.message.reply_text(response)

def main() -> None:
    # Загружаем токен из .env
    TOKEN = os.getenv('BOT_TOKEN')

    if not TOKEN:
        raise ValueError("Не найден токен бота в .env файле!")

    # Создаем приложение
    application = Application.builder().token(TOKEN).build()

    # Обработчики
    application.add_handler(CommandHandler("start", start))
    application.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, handle_message))

    # Запуск бота
    application.run_polling()

if __name__ == '__main__':
    main()